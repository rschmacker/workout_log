// Dates are stored as "YYYY-MM-DD" strings (like the Postgres "date" type).
// We always use the phone's local date, never UTC, so late-evening workouts
// don't end up on the next day.

export function toISODate(d: Date): string {
  const y = d.getFullYear()
  const m = String(d.getMonth() + 1).padStart(2, '0')
  const day = String(d.getDate()).padStart(2, '0')
  return `${y}-${m}-${day}`
}

export function todayISO(): string {
  return toISODate(new Date())
}

export function parseISODate(s: string): Date {
  const [y, m, d] = s.split('-').map(Number)
  return new Date(y, m - 1, d)
}

// "Wed, 15 Oct 2026"
export function formatDay(s: string): string {
  return parseISODate(s).toLocaleDateString('en-GB', {
    weekday: 'short',
    day: 'numeric',
    month: 'short',
    year: 'numeric',
  })
}
